#!/usr/bin/env bash
# Regenerates db/schema.sql, the installer data for bin/setup.sh, from the local development
# database. The file holds the full schema and the data a new install needs: settings, roles and
# profiles, picklists, fields and filters, workflows, the chart of accounts and so on. It holds NO
# users and none of the records (customers, documents, payments, journal entries, ...): the
# development database is copied to a scratch database named <name>_installer, scrubbed there by
# bin/lib/scrub-installer-db.php, dumped, and dropped again. The development database is only read.
# bin/setup.sh creates the administrator login with bin/create-admin.php.
#
# Run this yourself after DB-level changes you want new installs to pick up (Module Designer
# edits, workflows, picklists, a new module script, ...).
set -euo pipefail

DB_HOST="${DB_HOST:-127.0.0.1}"
DB_PORT="${DB_PORT:-3306}"
DB_NAME="${DB_NAME:-vtigercrm}"
DB_USER="${DB_USER:-root}"
DB_PASS="${DB_PASS:-}"
SCRATCH="${DB_NAME}_installer"

cd "$(dirname "$0")/.."
mkdir -p db
OUT="db/schema.sql"
TMP=$(mktemp)
trap 'rm -f "$TMP"; MYSQL_PWD="$DB_PASS" mysql -h"$DB_HOST" -P"$DB_PORT" -u"$DB_USER" -e "DROP DATABASE IF EXISTS \`$SCRATCH\`" 2>/dev/null || true' EXIT

export MYSQL_PWD="$DB_PASS"
my=(-h"$DB_HOST" -P"$DB_PORT" -u"$DB_USER")

# 1. a scratch copy of the development database
mysql "${my[@]}" -e "DROP DATABASE IF EXISTS \`$SCRATCH\`; CREATE DATABASE \`$SCRATCH\` CHARACTER SET utf8mb4;"
mysqldump --single-transaction --set-gtid-purged=OFF "${my[@]}" "$DB_NAME" > "$TMP"
mysql "${my[@]}" "$SCRATCH" < "$TMP"

# 2. scrub it (the script refuses any database whose name does not end in _installer)
php bin/lib/scrub-installer-db.php "$DB_HOST" "$DB_PORT" "$DB_USER" "$DB_PASS" "$SCRATCH"

# 3. dump the scrubbed copy: schema first, then data. --set-gtid-purged=OFF keeps this server's
# GTID state out of the file so it imports anywhere.
{
	echo "-- Generated by bin/dump-db.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
	echo "-- Installer data: no users, no records. bin/setup.sh creates the administrator (bin/create-admin.php)."
} > "$OUT"
mysqldump --no-data --set-gtid-purged=OFF "${my[@]}" "$SCRATCH" >> "$OUT"
mysqldump --no-create-info --single-transaction --set-gtid-purged=OFF "${my[@]}" "$SCRATCH" >> "$OUT"

echo "Wrote $OUT ($(du -h "$OUT" | cut -f1)): schema and settings, no users, no records."
echo "Review it, then: git add db/schema.sql && git commit && git push"
