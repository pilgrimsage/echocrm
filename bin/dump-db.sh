#!/usr/bin/env bash
# Regenerates db/schema.sql from the local vtigercrm database so a fresh
# clone can be brought up with bin/setup.sh instead of a manual dump/import
# each time. Run this yourself after DB-level changes you want new clones
# to pick up (Module Designer edits, workflows, picklists, etc.).
#
# vtiger_users is intentionally excluded from the data dump below, so no
# login credential ever lands in db/schema.sql. bin/reset-admin-login.sh
# sets a working login after import.
set -euo pipefail

DB_HOST="${DB_HOST:-127.0.0.1}"
DB_PORT="${DB_PORT:-3306}"
DB_NAME="${DB_NAME:-vtigercrm}"
DB_USER="${DB_USER:-root}"
DB_PASS="${DB_PASS:-}"

cd "$(dirname "$0")/.."
mkdir -p db
OUT="db/schema.sql"

mysql_args=(-h"$DB_HOST" -P"$DB_PORT" -u"$DB_USER")
if [ -n "$DB_PASS" ]; then
	mysql_args+=(-p"$DB_PASS")
fi

{
	echo "-- Generated by bin/dump-db.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
	echo "-- vtiger_users is intentionally excluded here; run bin/setup.sh then bin/reset-admin-login.sh."
} > "$OUT"

# Full schema, no data. --set-gtid-purged=OFF avoids embedding this
# server's GTID state, which would otherwise fail to import on a server
# with different GTID history (or GTID mode off entirely).
mysqldump --no-data --set-gtid-purged=OFF "${mysql_args[@]}" "$DB_NAME" >> "$OUT"

# Data for every table except vtiger_users.
mysqldump --no-create-info --single-transaction --set-gtid-purged=OFF \
	--ignore-table="$DB_NAME.vtiger_users" "${mysql_args[@]}" "$DB_NAME" >> "$OUT"

echo "Wrote $OUT (schema for all tables, data for all tables except vtiger_users)"
echo "Review it, then: git add db/schema.sql && git commit && git push"
